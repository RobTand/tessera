#!/usr/bin/env python3
"""What TORCHINDUCTOR_DETERMINISTIC=1 does on the torch that serves.

WHY THIS EXISTS.  ``docs/measurements/serving-compile-divergence-2026-09-02.md``
§3b counted the mechanism behind the one non-reproducible compiled arm: under a
single AOT key, with byte-identical ``cache_key_factors.json``, **120 of 196**
autotuned Triton kernels chose a different ``XBLOCK``/``num_warps`` on the second
build, because inductor picks those by timing candidates on the device at compile
time and the box was loaded.  The pinned torch names a knob for exactly that
mechanism (``torch/_inductor/config.py:1007-1009``) and
``docs/measurements/serve-build-identity-2026-09-02.md`` §4 wired it as
``TESSERA_SERVE_DETERMINISTIC=1`` -- while recording that **no arm was served with
it**, so what it actually does was never measured.  Issue #30 asks for that.

This is the half of the measurement that does not need a serve.  Matched pair:
two builds per arm, from a **fresh inductor cache directory each time**, and the
only difference between the arms is the environment variable.

THE OBSERVABLE, and why it is not the config attribute.  Reading
``torch._inductor.config.deterministic`` back *after* a compile has run reports
``False`` on the pinned torch **whether or not the flag is set** (measured: see
``knob.reads`` in the report).  So the module attribute is not evidence that the
flag was in force.  Two things generated by the compile are:

* the generated Triton kernel's own heuristics metadata carries
  ``'deterministic': True`` and gains ``has_loadstore_with_contiguous_rdim``
  (``torch/_inductor/codegen/triton.py:6200`` and ``:6251`` on the pinned build);
* ``*.best_config`` records -- the device-timed autotune choice, carrying the
  ``time_taken_ms`` that made it -- stop being written, because the benchmark
  that writes them is banned (``torch/_inductor/runtime/benchmarking.py:148-160``
  ``may_ban_benchmarking``) and algorithm selection switches to
  ``pick_deterministic_choice`` (``torch/_inductor/select_algorithm.py:3900``).

SCOPE.  This measures the knob on **torch**, on whatever torch runs it.  Run it
inside the serving image to measure the pinned one (2.13.0+cu130)::

    docker run --rm --gpus all -v /home/rob/tmp/x:/w --entrypoint bash \\
      vllm/vllm-openai:latest -c 'cd /w && python3 inductor_determinism_probe.py --out r.json'

It does **not** measure two vLLM serves of a real checkpoint.  The graph here is
a handful of reduction kernels; the served backbone autotuned 196.  So an
"off" arm that happens to agree here is **not** evidence that a real build is
reproducible, and this probe says nothing about the eager-vs-compiled KL gap
(#16), which is a different question about a different comparison.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

# Keys that record the measurement rather than the choice -- the same pair
# experiments/compile_build_forensics.py strips, for the same reason.
TIMING_KEYS = {"time_taken_ms", "triton_cache_hash"}
META_DETERMINISTIC = re.compile(r"'deterministic': (\w+)")
META_RDIM = re.compile(r"'has_loadstore_with_contiguous_rdim': (\w+)")
HEURISTIC = re.compile(r"@triton_heuristics\.(\w+)\(")


def _child(cache_dir: str, out_path: str) -> int:
    """One build, in a process of its own: compile, run, record what was written."""
    import torch

    import torch._inductor.config as inductor_config

    at_import = bool(inductor_config.deterministic)
    torch.manual_seed(0)
    dev = "cuda" if torch.cuda.is_available() else "cpu"

    class Block(torch.nn.Module):
        """rms-norm shaped: a row reduction, a broadcast divide, a pointwise tail.

        Reduction kernels are the shape that autotunes ``R0_BLOCK``/``num_warps``
        on this torch, which is the record class that differed 120 of 196 times.
        """

        def __init__(self, h: int) -> None:
            super().__init__()
            self.w = torch.nn.Parameter(torch.randn(h, dtype=torch.bfloat16).abs() + 0.5)

        def forward(self, x: torch.Tensor, residual: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
            residual = residual + x
            var = residual.float().pow(2).mean(-1, keepdim=True)
            y = (residual.float() * torch.rsqrt(var + 1e-6)).to(residual.dtype) * self.w
            y = y * torch.sigmoid(y) + residual
            return y, residual

    # ONE torch.compile per child.  A second compile in the same process is a
    # different regime -- see ``persistence`` below, which measures it on
    # purpose instead of averaging it into the arm.
    digests = []
    reads = [bool(inductor_config.deterministic)]
    h = int(os.environ.get("TESSERA_PROBE_HIDDEN", "8192"))
    with torch.no_grad():
        mod = Block(h).to(dev)
        compiled = torch.compile(mod, dynamic=True)
        for n in (7, 256, 2048):
            x = torch.randn(n, h, device=dev, dtype=torch.bfloat16)
            r = torch.randn(n, h, device=dev, dtype=torch.bfloat16)
            y, res = compiled(x, r)
            if dev == "cuda":
                torch.cuda.synchronize()
            # raw output bytes: two builds are compared bitwise, never by a
            # tolerance that would hide exactly what is being measured
            digests.append(
                [
                    hashlib.sha256(y.detach().cpu().view(torch.uint8).numpy().tobytes()).hexdigest(),
                    hashlib.sha256(res.detach().cpu().view(torch.uint8).numpy().tobytes()).hexdigest(),
                ]
            )
        reads.append(bool(inductor_config.deterministic))
        # persistence: a SECOND compile in the same process, same flag
        mod2 = Block(h // 2).to(dev)
        compiled2 = torch.compile(mod2, dynamic=True)
        x = torch.randn(256, h // 2, device=dev, dtype=torch.bfloat16)
        r = torch.randn(256, h // 2, device=dev, dtype=torch.bfloat16)
        compiled2(x, r)
        if dev == "cuda":
            torch.cuda.synchronize()
        reads.append(bool(inductor_config.deterministic))

    root = Path(cache_dir)
    configs = {}
    for p in sorted(root.rglob("*.best_config")):
        try:
            configs[str(p.relative_to(root))] = json.loads(p.read_text())
        except Exception:  # noqa: BLE001 - a truncated record is data, not a crash
            configs[str(p.relative_to(root))] = {"__unparsed__": True}

    kernels: dict[str, dict] = {}
    for p in sorted(root.rglob("*.py"), key=lambda q: q.stat().st_mtime):
        text = p.read_text(errors="replace")
        heuristics = HEURISTIC.findall(text)
        if not heuristics:
            continue
        kernels[hashlib.sha256(text.encode()).hexdigest()[:16]] = {
            "heuristics": sorted(set(heuristics)),
            "meta_deterministic": sorted(set(META_DETERMINISTIC.findall(text))),
            "meta_contiguous_rdim": sorted(set(META_RDIM.findall(text))),
            "mtime": p.stat().st_mtime,
        }

    Path(out_path).write_text(
        json.dumps(
            {
                "torch": torch.__version__,
                "env": os.environ.get("TORCHINDUCTOR_DETERMINISTIC"),
                "config_at_import": at_import,
                "config_reads": reads,
                "device": dev,
                "digests": digests,
                "configs": configs,
                "kernels": kernels,
            }
        )
    )
    return 0


def _strip(rec: dict) -> dict:
    return {k: v for k, v in rec.items() if k not in TIMING_KEYS}


def _compare(a: dict, b: dict) -> dict:
    ca, cb = a["configs"], b["configs"]
    both = sorted(set(ca) & set(cb))
    same_choice_new_time = different_choice = byte_identical = 0
    examples = []
    for k in both:
        if ca[k] == cb[k]:
            byte_identical += 1
        elif _strip(ca[k]) == _strip(cb[k]):
            same_choice_new_time += 1
        else:
            different_choice += 1
            da, db = _strip(ca[k]), _strip(cb[k])
            if len(examples) < 6:
                examples.append(
                    {
                        "record": k,
                        "changed": {
                            kk: [da.get(kk), db.get(kk)]
                            for kk in sorted(set(da) | set(db))
                            if da.get(kk) != db.get(kk)
                        },
                    }
                )
    meta = sorted({v for build in (a, b) for k in build["kernels"].values() for v in k["meta_deterministic"]})
    return {
        "autotune_records": {"a": len(ca), "b": len(cb)},
        "records_in_both": len(both),
        "only_in_a": len(set(ca) - set(cb)),
        "only_in_b": len(set(cb) - set(ca)),
        "byte_identical": byte_identical,
        "same_choice_different_measured_time": same_choice_new_time,
        "different_tuning_choice": different_choice,
        "examples": examples,
        "kernel_sources_identical": sorted(a["kernels"]) == sorted(b["kernels"]),
        "kernel_count": {"a": len(a["kernels"]), "b": len(b["kernels"])},
        "kernel_meta_deterministic": meta,
        "kernel_meta_contiguous_rdim": sorted(
            {v for build in (a, b) for k in build["kernels"].values() for v in k["meta_contiguous_rdim"]}
        ),
        "outputs_bitwise_equal": a["digests"] == b["digests"],
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", default=(os.environ.get("TMPDIR") or ".") + "/inductor_determinism")
    ap.add_argument("--out", default="inductor_determinism_probe.json")
    ap.add_argument("--child", nargs=2, metavar=("CACHE_DIR", "OUT"))
    args = ap.parse_args()

    if args.child:
        return _child(*args.child)

    work = Path(args.work)
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)

    arms = {}
    for arm, flag in (("off", "0"), ("on", "1")):
        builds = []
        for i in (0, 1):
            cache = work / f"{arm}{i}"
            cache.mkdir()
            env = dict(os.environ)
            env["TORCHINDUCTOR_CACHE_DIR"] = str(cache)
            env["TRITON_CACHE_DIR"] = str(cache / "triton")
            env["TORCHINDUCTOR_DETERMINISTIC"] = flag
            out = work / f"{arm}{i}.json"
            r = subprocess.run(
                [sys.executable, __file__, "--child", str(cache), str(out)],
                env=env,
                capture_output=True,
                text=True,
            )
            if r.returncode != 0:
                print(f"[{arm}{i}] build FAILED rc={r.returncode}\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}")
                return 1
            builds.append(json.loads(out.read_text()))
        arms[arm] = {"builds": builds, "compare": _compare(*builds)}

    report = {
        "schema": "tessera.inductor_determinism_probe/1",
        "torch": arms["off"]["builds"][0]["torch"],
        "device": arms["off"]["builds"][0]["device"],
        "knob": {
            "env": "TORCHINDUCTOR_DETERMINISTIC",
            "config": "torch._inductor.config.deterministic",
            "reads": {
                arm: {
                    "at_import": [b["config_at_import"] for b in v["builds"]],
                    "after_first_compile": [b["config_reads"][1] for b in v["builds"]],
                    "after_second_compile": [b["config_reads"][2] for b in v["builds"]],
                }
                for arm, v in arms.items()
            },
        },
        "arms": {k: v["compare"] for k, v in arms.items()},
    }
    Path(args.out).write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
