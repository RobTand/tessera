#!/usr/bin/env python3
"""Write every generated BUILD.bazel from Tessera's dependency evidence.

Gazelle can't express Tessera's imports: modules import each other in cycles
through function-local imports, tests import other test modules (a py_test
can't be a dependency), tests put experiment directories on sys.path at run
time, and tests run tools by path. tools/bazel/evidence.py reads all of these
from the source, and this generator turns them into targets:

- one py_library per module, and one per import cycle;
- two tests per test file, one per hosted gate lane: `test_x` runs with the
  CPU torch wheel, `test_x.bytes` without torch, as the gate's no-torch lane
  does;
- data for every file a module names by path;
- the gate's node-level quarantine as deselects, and Bazel test shards for
  files that take long on hosted runners.

Run tools/bazel/generate.sh after adding a module, test, import or fixture.
--check fails, naming each stale file, when a committed BUILD.bazel differs.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import json
import math
from pathlib import Path, PurePosixPath
import re
import shlex
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from evidence import (HANDWRITTEN, PACKAGES, ROOT, Evidence, is_test, is_test_side,  # noqa: E402
                      package_of, repository_files)
from graph import CONFTEST, Graph, strongly_connected  # noqa: E402

FIX = 'tools/bazel/generate.sh'
HEADER = '# Generated by tools/bazel/generate.sh from Tessera\'s dependency evidence. Do not edit.\n'
TREE_LABEL = re.compile(r'"//([\w/]*):files(/[\w./-]+)?"')
GLOB_EXCLUDE = ['**/BUILD.bazel', 'bazel-*/**', '*bazel-remote-grpc.log', '*execution_log.binpb.zst',
                '.pytest_cache/**', '**/__pycache__/**', '**/*.pyc']
# Files longer than this on hosted runners are split across Bazel test shards.
SHARD_SECONDS = 40.0
MAX_SHARDS = 8
# Files whose tests depend on each other within the module, so a Bazel shard
# that holds only some of them fails. Each names the issue that owns the fix.
UNSHARDED = {
    'tests/test_audit_byte_baseline.py': 'its batch-row test counts encode calls the other tests in the module record',
}
CONTRACT = 'src/tessera/serving/runtime_contract.json'
CONTRACT_PATH = re.compile(r'[\w.-]+(?:/[\w.-]+)+')
LANES = ('torch', 'bytes')
DURATIONS = 'tools/ci/gate_durations.json'
QUARANTINE = 'tools/ci/gate_quarantine.json'
FLAKY = 'tools/ci/gate_flaky.json'
BUDGET = 'tools/ci/gate_budget.json'
REQUIREMENTS = {'bytes': 'tools/ci/gate_requirements.txt', 'torch': 'tools/ci/gate_torch_requirements.txt'}
PIN = re.compile(r'^([A-Za-z0-9][A-Za-z0-9._-]*)(?:==|\s*@)', re.MULTILINE)


class GenerationError(RuntimeError):
    """The evidence can't become a valid Bazel graph. Generation fails."""


def relative(path, package):
    return path[len(package) + 1:] if package else path


def library_name(path):
    stem = relative(path, package_of(path)).removesuffix('.py')
    # The test target takes the file's name; its importable module needs another.
    return stem + '_lib' if is_test(path) else stem


def label(package, name, home):
    return f':{name}' if package == home else f'//{package}:{name}'


def file_label(path, home):
    package = package_of(path)
    return relative(path, package) if package == home else f'//{package}:{relative(path, package)}'


def tree_name(directory):
    return 'files/' + directory if directory else 'files'


class Trees:
    """Name a set of files by the fewest labels: a directory whose every file is
    in the set becomes one filegroup in its package."""

    def __init__(self, files):
        self.under = defaultdict(set)
        for path in files:
            package = package_of(path)
            parts = PurePosixPath(relative(path, package)).parts
            for end in range(len(parts)):
                self.under[(package, '/'.join(parts[:end]))].add(path)
        self.used = defaultdict(set)

    def labels(self, files, home):
        remaining, labels = set(files), set()
        for (package, directory), members in sorted(self.under.items(), key=lambda item: item[0][1].count('/')
                                                     + bool(item[0][1])):
            if package == HANDWRITTEN[0].rstrip('/') and directory:
                continue
            if len(members) > 1 and members <= remaining:
                remaining -= members
                self.used[package].add(directory)
                labels.add(label(package, tree_name(directory), home))
        return sorted(labels | {file_label(path, home) for path in remaining})


def strings(values, indent='        '):
    if not values:
        return '[]'
    return '[\n' + ''.join(f'{indent}{json.dumps(value)},\n' for value in values) + indent[:-4] + ']'


def gate_tables(root):
    """(per-lane durations, per-lane quarantined nodes) from the hosted gate's own files."""
    durations = json.loads((root / DURATIONS).read_text())['lanes']
    quarantine = json.loads((root / QUARANTINE).read_text())['lanes']
    return durations, quarantine


def lane_packages(root):
    """The pip packages each lane installs, by the names its requirements file pins."""
    bytes_ = [name for name in PIN.findall((root / REQUIREMENTS['bytes']).read_text())]
    torch = [name for name in PIN.findall((root / REQUIREMENTS['torch']).read_text())]
    return {'bytes': sorted(set(bytes_)), 'torch': sorted(set(bytes_) | set(torch))}


def test_attributes(path, lane, durations, quarantine, budget):
    """args, shard_count and timeout for one test file in one lane.

    The file's slice of the gate's budgets travels as an argument, so a budget
    change reruns only the file it names.
    """
    attributes = {'lane': lane}
    deselect = [node for node in quarantine.get(lane, []) if node.split('::', 1)[0] == path]
    own = {'seconds': budget['seconds'], 'enforce': budget.get('enforce', False),
           'slow': {node: limit for node, limit in sorted(budget['slow'].items()) if node.split('::', 1)[0] == path}}
    # Bazel tokenizes args like a shell, so the JSON is shell-quoted.
    attributes['args'] = ['--budget=' + shlex.quote(json.dumps(own, sort_keys=True, separators=(',', ':')))]
    if path in deselect:
        attributes['tags'] = ['manual', 'gate-quarantine']
    elif deselect:
        attributes['args'] += ['--deselect=' + node for node in deselect]
    seconds = durations.get(lane, {}).get(path)
    if seconds is not None and seconds > SHARD_SECONDS and path not in UNSHARDED:
        shards = min(MAX_SHARDS, math.ceil(seconds / SHARD_SECONDS))
        attributes['shard_count'] = shards
        seconds /= shards
    # A slow node stays in one shard. Averaging the file's time across shards
    # must not cut off that node before its existing hosted-gate allowance.
    needed = max(seconds or 0, own['seconds'], *own['slow'].values()) * 3
    attributes['timeout'] = next((name for name, limit in (
        ('moderate', 300), ('long', 900), ('eternal', 3600)) if limit >= needed), None)
    if attributes['timeout'] is None:
        raise GenerationError(f'{path} ({lane}) needs {needed:g}s, beyond Bazel\'s maximum timeout')
    return attributes


def generate(root=ROOT, files=None):
    """{package directory: BUILD.bazel text} for every generated package."""
    graph = Graph(Evidence(root, files))
    files = graph.evidence.files
    evidence, edges, data = graph.evidence, graph.edges, graph.data
    owner, libraries = {}, []
    for component in strongly_connected(evidence.modules, edges):
        packages = {package_of(path) for path in component}
        if len(packages) > 1:
            raise GenerationError('an import cycle crosses Bazel packages, which no target can hold: '
                                  + ', '.join(component))
        name = library_name(component[0]) + ('_cycle' if len(component) > 1 else '')
        for path in component:
            owner[path] = (package_of(path), name)
        libraries.append(component)
    durations, quarantine = gate_tables(root)
    budget = json.loads((root / BUDGET).read_text())
    trees = Trees(files)
    # Filegroups tools/bazel/test_inputs.bzl names must exist.
    for package, directory in TREE_LABEL.findall((root / 'tools/bazel/test_inputs.bzl').read_text()):
        trees.used[package].add(directory.removeprefix('/'))
    packages = {package: [] for package in ('', *PACKAGES)}
    for component in libraries:
        home, name = owner[component[0]]
        deps = sorted({label(*owner[target], home) for path in component for target in edges[path]}
                      - {label(home, name, home)})
        inputs = trees.labels({file for path in component for file in data[path]} - set(component), home)
        packages[home].append((name, 'ts_py_library', {
            'srcs': [relative(path, home) for path in component], 'data': inputs, 'deps': deps}))
    for path in graph.tests:
        home = package_of(path)
        stem = relative(path, home).removesuffix('.py')
        own = trees.labels(graph.test_data(path) | graph.script_files(path), home)
        programs = sorted({label(*owner[module], home) for module in graph.launched(path)}
                          - {label(*owner[path], home)})
        for lane in LANES:
            name = stem if lane == 'torch' else f'{stem}.bytes'
            packages[home].append((name, 'ts_py_test', {
                'path': path, 'library': label(*owner[path], home), 'data': own, 'deps': programs,
                **test_attributes(path, lane, durations, quarantine, budget)}))
    # gate_collect validates the existence of every file named by the flaky
    # table before collecting any assignment. These are data, not imports.
    flaky_files = {node.split('::', 1)[0] for node in json.loads((root / FLAKY).read_text())}
    packages['tests'].append(('gate_flaky_inputs', 'filegroup', {
        'srcs': sorted(relative(path, 'tests') for path in flaky_files)}))
    # The repository paths runtime_contract.json names, in prose too: the
    # contract tests check that each one exists (tools/bazel/test_inputs.bzl).
    named = {match.rstrip('.') for match in CONTRACT_PATH.findall((root / CONTRACT).read_text())}
    packages['src/tessera'].append(('runtime_contract_paths', 'filegroup', {
        'srcs': trees.labels(named & set(files), 'src/tessera')}))
    for package, directories in trees.used.items():
        if package == HANDWRITTEN[0].rstrip('/'):
            continue  # Its BUILD file, written by hand, declares :files.
        for directory in directories:
            packages[package].append((tree_name(directory), 'filegroup', {
                'srcs': sorted(relative(path, package) for path in trees.under[package, directory])}))
    rendered = {package: render_package(package, targets) for package, targets in packages.items()}
    tool_files = sorted(relative(path, 'tools/bazel') for path in files if path.startswith('tools/bazel/'))
    rendered['tools/bazel/lanes.bzl'] = render_lanes(lane_packages(root), owner[CONFTEST], tool_files)
    return rendered


def render_lanes(packages, conftest, tool_files):
    lines = [HEADER, '"""Hosted gate packages, shared conftest, and Bazel tool source inputs."""\n']
    for lane in LANES:
        lines.append(f'{lane.upper()}_PACKAGES = {strings(packages[lane], "    ")}\n')
    lines.append(f'CONFTEST = "//{conftest[0]}:{conftest[1]}"\n')
    lines.append(f'BAZEL_TOOL_FILES = {strings(tool_files, "    ")}\n')
    return '\n'.join(lines)


def render_package(package, targets):
    names = [name for name, _, _ in targets]
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        raise GenerationError(f'two targets named {duplicates} in //{package}; rename a module')
    kinds = sorted({kind for _, kind, _ in targets} - {'filegroup'})
    lines = [HEADER]
    if kinds:
        lines.append('load("//tools/bazel:python.bzl", ' + ', '.join(f'"{kind}"' for kind in kinds) + ')\n')
    lines.append('package(default_visibility = ["//visibility:public"])\n')
    lines.append('# Other packages name these files as test data.\n'
                 f'exports_files(glob(["**"], exclude = {json.dumps(GLOB_EXCLUDE)}))\n')
    for name, kind, attributes in sorted(targets):
        body = [f'    name = {json.dumps(name)},\n']
        for key, value in attributes.items():
            if value in ([], None):
                continue
            rendered = (strings(value) if isinstance(value, list) else
                        value if key == 'srcs' and isinstance(value, str) else json.dumps(value))
            body.append(f'    {key} = {rendered},\n')
        lines.append(f'{kind}(\n' + ''.join(body) + ')\n')
    return '\n'.join(lines)


def output_path(root, key):
    return root / key if key.endswith('.bzl') else root / key / 'BUILD.bazel'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args(argv)
    try:
        generated = generate(args.root)
    except GenerationError as error:
        sys.exit(f'Cannot generate BUILD files: {error}')
    stale = []
    for key, text in sorted(generated.items()):
        path = output_path(args.root, key)
        if path.exists() and path.read_text() == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(args.root)))
        else:
            path.write_text(text)
    if stale:
        sys.exit('Generated BUILD files are stale: ' + ', '.join(stale) + f'\nFix: {FIX}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
