#!/usr/bin/env python3
"""Export or check pip.parse's hashed requirements from the hosted gate's pins.

tools/ci/gate_requirements.txt (the no-torch lane) and
tools/ci/gate_torch_requirements.txt (added by the torch lane) are what every
hosted gate shard installs, so they are the source of truth. The export
resolves both once, with hashes, for Linux x86_64 and aarch64, as of a recorded
date so it reproduces. torch resolves from PyTorch's CPU index only. --check
needs no network: the export must name the sources' sha256 and pin every
package the sources pin at the same version.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ('tools/ci/gate_requirements.txt', 'tools/ci/gate_torch_requirements.txt',
           'tools/ci/gate_prismaquant_requirements.txt')
EXPORT = 'tools/bazel/requirements.txt'
FIX = 'python3 tools/bazel/requirements.py'
EXCLUDE_NEWER = '2026-11-02T00:00:00Z'
CPU_INDEX = 'https://download.pytorch.org/whl/cpu'
INDEX_LINE = re.compile(r'^--(?:extra-)?index-url\s+\S+\s*$', re.MULTILINE)
PIN = re.compile(r'^([A-Za-z0-9][A-Za-z0-9._-]*)(?:==([^\s;\\]+)|\s*@\s*(\S+))', re.MULTILINE)


def normal(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def pins(text):
    return {normal(name): version or url for name, version, url in PIN.findall(text)}


def source_text(root):
    return ''.join((root / source).read_text() for source in SOURCES)


def header(source):
    digest = hashlib.sha256(source.encode()).hexdigest()
    return (f'# Generated by {FIX} from {" and ".join(SOURCES)}; do not edit.\n'
            f'# source-sha256: {digest}\n# exclude-newer: {EXCLUDE_NEWER}\n'
            f'# torch comes from {CPU_INDEX} (MODULE.bazel experimental_index_url_overrides);\n'
            f'# every other package from PyPI, one wheel per platform.\n')


def problems(source, export):
    """Why the export no longer matches the sources; empty when it does."""
    found = []
    if not export.startswith(header(source)):
        found.append(f'{EXPORT} was not generated from the current {" and ".join(SOURCES)}')
    exported = pins(export)
    for name, version in sorted(pins(source).items()):
        if exported.get(name) != version:
            found.append(f'the gate pins {name} {version}; {EXPORT} has {exported.get(name)}')
    return found


def export(source):
    """Resolve the pins once for both platforms. torch, and only torch, comes
    from the CPU index: that index also serves its own triton builds, whose
    aarch64 wheel is tagged linux_aarch64, which pip.parse can't select for
    an arm64 executor."""
    requirements = [line.strip() for line in INDEX_LINE.sub('', source).splitlines()
                    if line.strip() and not line.strip().startswith('#')]
    project = ('[project]\nname = "tessera-gate-pins"\nversion = "0"\nrequires-python = ">=3.12"\n'
               f'dependencies = {json.dumps(requirements)}\n'
               '[tool.uv.sources]\ntorch = { index = "pytorch-cpu" }\n'
               f'[[tool.uv.index]]\nname = "pytorch-cpu"\nurl = "{CPU_INDEX}"\nexplicit = true\n')
    with tempfile.TemporaryDirectory() as temporary:
        pyproject, output = Path(temporary, 'pyproject.toml'), Path(temporary, 'out.txt')
        pyproject.write_text(project)
        subprocess.run(['uv', 'pip', 'compile', str(pyproject), '--universal', '--generate-hashes',
                        '--python-version', '3.12', '--exclude-newer', EXCLUDE_NEWER,
                        '--no-header', '--no-annotate', '--quiet', '--output-file', str(output)],
                       check=True)
        return output.read_text()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args(argv)
    source = source_text(args.root)
    if args.check:
        found = problems(source, (args.root / EXPORT).read_text())
        if found:
            sys.exit('Bazel requirements drifted:\n' + '\n'.join(found) + f'\nFix: {FIX}')
        return 0
    (args.root / EXPORT).write_text(header(source) + export(source))
    return 0


if __name__ == '__main__':
    sys.exit(main())
